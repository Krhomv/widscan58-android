#!/usr/bin/env python3
"""Generates src/fonts.cpp: anti-aliased bitmap fonts (4 bits of coverage per
pixel) rendered from Inter with Pillow. Run from handheld/:

    python3 tools/make_fonts.py /path/to/Inter/otf

Inter is (c) The Inter Project Authors, SIL Open Font License 1.1; the
generated bitmaps are a derivative of it under the same license.
GPL-3.0-or-later for this script."""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

# (C name, file, pixel size)
FONTS = [
    ("font_title", "Inter-SemiBold.otf", 15),
    ("font_label", "Inter-SemiBold.otf", 12),
    ("font_small", "Inter-Regular.otf", 11),
    ("font_big", "Inter-SemiBold.otf", 22),
]
# Printable ASCII plus the few others the UI draws.
CODES = list(range(32, 127)) + [0xB7, 0x2013, 0x2026, 0x2265, 0x00B0]


def render(path, size):
    font = ImageFont.truetype(str(path), size)
    ascent, descent = font.getmetrics()
    glyphs, bits = [], bytearray()
    for cp in sorted(CODES):
        ch = chr(cp)
        adv = round(font.getlength(ch))
        l, t, r, b = font.getbbox(ch, anchor="ls")
        w, h = max(0, r - l), max(0, b - t)
        off = len(bits)
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-l, -t), ch, font=font, fill=255, anchor="ls")
            px = im.tobytes()
            nib = [min(15, (v + 8) // 17) for v in px]
            if len(nib) % 2:
                nib.append(0)
            for j in range(0, len(nib), 2):
                bits.append(nib[j] << 4 | nib[j + 1])
        glyphs.append((cp, off, w, h, l, t, adv))
    return ascent, descent, glyphs, bits


def main():
    src = Path(sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/opentype/inter")
    out = ["// Generated by tools/make_fonts.py from Inter (c) The Inter Project Authors,",
           "// SIL Open Font License 1.1. Do not edit.",
           '#include "fonts.h"', ""]
    for name, file, size in FONTS:
        ascent, descent, glyphs, bits = render(src / file, size)
        out.append(f"static const uint8_t {name}_bits[] = {{")
        for j in range(0, len(bits), 24):
            out.append("    " + ", ".join(f"0x{b:02x}" for b in bits[j:j + 24]) + ",")
        out.append("};")
        out.append(f"static const Glyph {name}_glyphs[] = {{")
        for cp, off, w, h, l, t, adv in glyphs:
            out.append(f"    {{0x{cp:04x}, {off}, {w}, {h}, {l}, {t}, {adv}}},")
        out.append("};")
        out.append(f"const Font {name} = {{{name}_bits, {name}_glyphs, {len(glyphs)}, {ascent}, {descent}}};")
        out.append("")
    Path("src/fonts.cpp").write_text("\n".join(out))


main()
